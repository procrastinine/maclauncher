const fs = require("node:fs");
const path = require("node:path");
const SOURCE_REVISION = "06cd1340cbc6150e7ca6769c61c5db20b24c0d51";
const MAX_SCRIPT_BYTES = 8 * 1024 * 1024;
const MAX_TOTAL_BYTES = 24 * 1024 * 1024;

function readText(file, limit) {
  const stat = fs.lstatSync(file);
  if (!stat.isFile() || stat.size > limit) return null;
  return fs.readFileSync(file, "utf8");
}
function extractVersion(source, prefix) {
  const parts = ["MajorVersion", "MinorVersion", "BuildVersion", "RevisionVersion"].map(field => {
    const match = source.match(new RegExp(`(?:^|[,{]\\s*)["']?${prefix}${field}["']?\\s*:\\s*["']?(\\d+)["']?(?=\\s*[,}])`));
    return match ? Number(match[1]) : null;
  });
  return parts.every(part => Number.isSafeInteger(part) && part >= 0) ? parts.join(".") : null;
}
function inspectExport(indexHtml, contentRoot) {
  const html = readText(indexHtml, 512 * 1024);
  if (!html) return null;
  const scripts = [], seen = new Set();
  for (const match of html.matchAll(/<script\b[^>]*\bsrc\s*=\s*["']([^"']+)["'][^>]*>/gi)) {
    let src = match[1].replace(/&amp;/gi, "&").split(/[?#]/)[0];
    if (!src || /^[a-z][a-z0-9+.-]*:|^\/\//i.test(src)) continue;
    try { src = decodeURIComponent(src); } catch { continue; }
    const candidate = path.resolve(path.dirname(indexHtml), src);
    const relative = path.relative(contentRoot, candidate);
    if (relative.startsWith("..") || path.isAbsolute(relative) || !candidate.toLowerCase().endsWith(".js") || seen.has(candidate)) continue;
    try {
      const actualRelative = path.relative(fs.realpathSync(contentRoot), fs.realpathSync(candidate));
      if (actualRelative.startsWith("..") || path.isAbsolute(actualRelative)) continue;
    } catch { continue; }
    seen.add(candidate);
    scripts.push(candidate);
    if (scripts.length >= 24) break;
  }
  let scannedBytes = 0;
  let hasInit = /\bGameMaker_Init\s*\(/.test(html);
  let hasData = /\bJSON_game\b/.test(html);
  let hasRuntimeLoad = false;
  const generatedIndex = /<!--\s*Generated by GameMaker(?::Studio)?\b/i.test(html) && /<canvas\b/i.test(html);
  let productionRuntime = false;
  let compilerVersion = null, appVersion = null, versionSource = null;
  const evidence = [];
  for (const script of scripts) {
    let source;
    try { source = readText(script, Math.min(MAX_SCRIPT_BYTES, MAX_TOTAL_BYTES - scannedBytes)); } catch { continue; }
    if (!source) continue;
    scannedBytes += Buffer.byteLength(source);
    hasInit ||= /\bGameMaker_Init\b/.test(source);
    hasData ||= /\bJSON_game\b/.test(source);
    hasRuntimeLoad ||= /\bg_pGMFile\b/.test(source) && /\b(?:LoadGame|yyObject|gml_Script_\w+)\b/.test(source);
    // Production exports rename their data/runtime globals. Public entry and
    // conversion helpers remain identifiable; require their actual declarations
    // together with the generated canvas index and GML script-symbol metadata.
    productionRuntime ||= generatedIndex && source.length >= 32768 &&
      /\bfunction\s+GameMaker_Init\s*\(/.test(source) && /\bg_GameMakerHTML5Dir\b/.test(source) &&
      /\bfunction\s+yyGetString\s*\(/.test(source) && /\bfunction\s+yyGetInt32\s*\(/.test(source) &&
      /\bgml_(?:Script|GlobalScript|Object)_[A-Za-z0-9_]+\b/.test(source);
    const version = extractVersion(source, "AssetCompiler");
    if (version) { compilerVersion = version; versionSource = path.relative(contentRoot, script); }
    appVersion ||= extractVersion(source, "");
    evidence.push(path.relative(contentRoot, script));
  }
  if (!hasInit || !(hasData && hasRuntimeLoad) && !productionRuntime) return null;
  return { detectedVersion: compilerVersion, detectedSource: compilerVersion ? `Declared asset compiler fields in ${versionSource}` : "Export does not declare a complete compiler version",
    detectedConfidence: compilerVersion ? "declared" : "unknown", appVersion, evidence, scannedBytes, runtimeSourceRevision: SOURCE_REVISION,
    signatureKind: hasData && hasRuntimeLoad ? "named-export-data" : "obfuscated-production-runtime",
    obfuscated: !(hasData && hasRuntimeLoad) };
}
function detectGame(context, helpers) {
  const roots = context.isAppBundle ? [
    path.join(context.rootDir, "Contents/Resources/app.nw"), path.join(context.rootDir, "Contents/Resources/app")
  ] : [context.rootDir];
  for (const root of roots) {
    const index = context.stat?.isFile?.() && /\.html?$/i.test(context.inputPath) ? context.inputPath : helpers.findIndexHtml(root);
    if (!index) continue;
    let metadata;
    try { metadata = inspectExport(index, root); } catch { continue; }
    if (!metadata) continue;
    return { engine: "gamemaker-html5", moduleId: "gamemaker-html5", gameType: "web", gamePath: context.rootDir, contentRootDir: root,
      name: path.basename(context.rootDir, context.isAppBundle ? ".app" : undefined), indexHtml: index, indexDir: path.dirname(index), moduleData: metadata };
  }
  return null;
}
module.exports = { detectGame, inspectExport, extractVersion, SOURCE_REVISION };
