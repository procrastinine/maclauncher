const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const test = require("node:test");
const { inspectExport, extractVersion } = require("../src/modules/gamemaker-html5/detect");
const mod = require("../src/modules/gamemaker-html5/main");
const Registry = require("../src/modules/registry");

function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "maclauncher-gm-html5-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.mkdirSync(path.join(root, "html5game"));
  fs.writeFileSync(path.join(root, "index.html"), '<script src="html5game/game.js?cache=1"></script><script>GameMaker_Init();</script>');
  fs.writeFileSync(path.join(root, "html5game/game.js"), 'function GameMaker_Init(){g_pGMFile=JSON_game;LoadGame(g_pGMFile)};var JSON_game={Options:{AssetCompilerMajorVersion:2024,AssetCompilerMinorVersion:14,AssetCompilerBuildVersion:2,AssetCompilerRevisionVersion:123,MajorVersion:1,MinorVersion:0,BuildVersion:0,RevisionVersion:7}};');
  return root;
}
test("prepared export detection separates declared compiler version from game app version", t => {
  const root = fixture(t);
  const info = inspectExport(path.join(root, "index.html"), root);
  assert.equal(info.detectedVersion, "2024.14.2.123");
  assert.equal(info.appVersion, "1.0.0.7");
  assert.equal(info.detectedConfidence, "declared");
  const detected = Registry.detectGame(root);
  assert.equal(detected.engine, "gamemaker-html5");
});
test("runtime names alone, remote scripts and parent traversal do not classify generic HTML", t => {
  const root = fixture(t), index = path.join(root, "index.html");
  fs.writeFileSync(index, '<p>GameMaker_Init and JSON_game</p><script src="https://remote.example/game.js"></script><script src="../outside.js"></script>');
  assert.equal(inspectExport(index, root), null);
});
test("missing compiler fields remain unknown and detection does not execute exported JavaScript", t => {
  const root = fixture(t), source = path.join(root, "html5game/game.js");
  fs.writeFileSync(source, 'throw new Error("must never execute"); var JSON_game={};function GameMaker_Init(){g_pGMFile=JSON_game;LoadGame(g_pGMFile)}');
  const detected = mod.detectGame({ rootDir: root, stat: fs.statSync(root) }, { findIndexHtml: Registry.findIndexHtml });
  assert.equal(detected.moduleData.detectedVersion, null);
  assert.equal(detected.moduleData.detectedConfidence, "unknown");
  assert.equal(extractVersion('{MajorVersion:1,MinorVersion:0}', ""), null);
});
test("obfuscated production exports retain bounded public runtime declarations without requiring renamed data globals", t => {
  const root = fixture(t), index = path.join(root, "index.html"), script = path.join(root, "html5game/game.js");
  fs.writeFileSync(index, '<!-- Generated by GameMaker:Studio http://www.yoyogames.com/gamemaker/studio --><canvas id="canvas"></canvas><script src="html5game/game.js"></script><script>window.onload=GameMaker_Init;</script>');
  const runtime = 'function GameMaker_Init(){};var g_GameMakerHTML5Dir;function yyGetString(x){return String(x)};function yyGetInt32(x){return x|0};var _renamed=["gml_GlobalScript_start"];' + '/* actual generated runtime bytes */'.repeat(1100);
  fs.writeFileSync(script, runtime);
  const info = inspectExport(index, root);
  assert.equal(info.signatureKind, "obfuscated-production-runtime"); assert.equal(info.obfuscated, true);
  assert.equal(info.detectedVersion, null); assert.equal(info.detectedConfidence, "unknown");
  fs.writeFileSync(script, runtime.replace('function yyGetInt32', 'function arbitraryNumber'));
  assert.equal(inspectExport(index, root), null);
  fs.writeFileSync(script, runtime); fs.writeFileSync(index, '<canvas></canvas><script src="html5game/game.js"></script>');
  assert.equal(inspectExport(index, root), null, "a generic canvas/script page lacks exporter evidence");
});
