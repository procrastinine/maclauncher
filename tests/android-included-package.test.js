const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const test = require("node:test");
const { pathToFileURL } = require("node:url");
const B = require("../src/modules/shared/runtime/bundled-native");
const Included = require("../src/modules/shared/runtime/included-helpers");
const Source = require("../src/modules/android/runtime-source");
const RuntimePackages = require("../scripts/runtime-packages.cjs");

test("the Android included package installs offline, loads physical interfaces and rejects corruption", async t => {
  const pin = require("../src/modules/android/distribution-included.json").find(item => item.id === "android-launcher");
  assert.ok(pin);
  const archive = path.resolve(__dirname, "../build/included-helper-packages", `${pin.id}-${pin.version}-${pin.arch}.tar.gz`);
  if (!fs.existsSync(archive)) return t.skip("Requires the locally prepared Android included package archive");
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "android-included-package-")));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const directory = path.join(root, "native-runtimes", pin.directoryRelative); fs.mkdirSync(directory, { recursive: true });
  const record = JSON.parse(fs.readFileSync(archive + ".json"));
  const installed = await RuntimePackages.extractPackage(archive, directory, record);
  B.verifyPayload(directory, installed);
  const selection = { id: pin.id, version: pin.version, resourcesRoot: root, verification: "full" };
  assert.equal(Included.resolveIncluded([pin], selection).directory, directory);
  assert.equal(Included.resolveIncluded([pin], selection).directory, directory, "offline reuse reads only the installed package");
  const sourceRoot = path.join(directory, "files/runtime");
  const sourceMembers = pin.files.filter(item => item.path.startsWith("files/runtime/"));
  assert.equal(sourceMembers.length, 12, "the launcher-facing source closure is complete");
  for (const member of sourceMembers) assert.equal(B.readRegular(path.join(directory, member.path), B.LIMITS.fileBytes).sha256, member.sha256);
  const apkPath = Source.file("apk.js", { sourceRoot });
  assert.equal(fs.realpathSync(apkPath), apkPath, "Node loads an ordinary physical file");
  const Apk = require(apkPath), manifest = Apk.inspectApk(path.join(__dirname, "fixtures/android-package-metadata/metadata.apk"));
  assert.equal(manifest.packageName, "org.maclauncher.metadata.fixture");
  assert.equal(typeof require(Source.file("profile.js", { sourceRoot })).runtimeProfile, "function");
  assert.equal(typeof require(Source.file("art/runtime.js", { sourceRoot })).attachSupplier, "function");
  const boot = await import(pathToFileURL(Source.file("art/boot-classpath.mjs", { sourceRoot })).href);
  assert.deepEqual(boot.runtimeBootClasspath(["/system/framework/framework.jar"]), ["/system/framework/framework.jar", "/system/framework/services.jar", "/system/framework/maclauncher.jar"]);
  const jar = path.join(directory, "files/resources/launch-arguments.jar"), original = fs.readFileSync(jar);
  const changed = Buffer.from(original); changed[changed.length - 1] ^= 1; fs.writeFileSync(jar, changed);
  assert.throws(() => Included.resolveIncluded([pin], selection), /checksum|changed/);
  fs.writeFileSync(jar, original);
  const policy = Source.file("native/resources/storage-namespace.json", { sourceRoot }), bytes = fs.readFileSync(policy);
  fs.writeFileSync(policy, Buffer.alloc(bytes.length));
  assert.throws(() => Included.resolveIncluded([pin], selection), /checksum|changed/);
});
