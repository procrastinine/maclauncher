const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const test = require("node:test");
const Renpy = require("../src/modules/renpy/main");
const { FILE_NAME, installDeveloperTools, removeDeveloperTools } = require("../src/modules/renpy/developer-tools");

test("console patch is opt-in, preserves game scripts, validates options, and removes owned compiled files", t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "renpy-tools-console-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const gameDir = path.join(root, "game");
  fs.mkdirSync(gameDir);
  fs.writeFileSync(path.join(gameDir, "script.rpy"), "original");
  const entry = { gamePath: root };
  assert.equal(Renpy.actions.renpyCheatsStatus(entry).consolePresent, false);
  const result = Renpy.actions.installRenpyConsole(entry, {});
  assert.equal(result.consoleInstalled, true);
  assert.equal(result.restartRequired, true);
  let source = fs.readFileSync(path.join(gameDir, FILE_NAME), "utf8");
  assert.match(source, /config.console = True/);
  assert.doesNotMatch(source, /config.developer|config.fast_skipping/);
  assert.doesNotMatch(source, /urllib|socket|requests|save_token/);
  fs.writeFileSync(path.join(gameDir, FILE_NAME + "c"), "compiled");
  installDeveloperTools(gameDir, { developer: true, fastSkip: true });
  source = fs.readFileSync(path.join(gameDir, FILE_NAME), "utf8");
  assert.match(source, /config.developer = True/);
  assert.match(source, /config.fast_skipping = True/);
  assert.equal(fs.existsSync(path.join(gameDir, FILE_NAME + "c")), false);
  assert.throws(() => installDeveloperTools(gameDir, { developer: "true" }), /boolean/);
  fs.writeFileSync(path.join(gameDir, FILE_NAME + "c"), "compiled");
  assert.equal(removeDeveloperTools(gameDir).consolePresent, false);
  assert.equal(fs.existsSync(path.join(gameDir, FILE_NAME + "c")), false);
  assert.equal(fs.readFileSync(path.join(gameDir, "script.rpy"), "utf8"), "original");
  fs.writeFileSync(path.join(gameDir, FILE_NAME), "third-party file");
  assert.throws(() => installDeveloperTools(gameDir), /refusing to overwrite/);
  assert.throws(() => removeDeveloperTools(gameDir), /refusing to remove/);
  fs.rmSync(path.join(gameDir, FILE_NAME));
  fs.symlinkSync(path.join(gameDir, "script.rpy"), path.join(gameDir, FILE_NAME));
  assert.throws(() => installDeveloperTools(gameDir), /regular files/);
});
