const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const EasyRPG = require("../src/modules/easyrpg/backcompat");
const GameData = require("../src/modules/shared/game-data");

const userDataDir = path.resolve("/tmp/easyrpg-mirror-descriptor-profile");
const sourceRoot = path.resolve("/tmp/easyrpg-original-project");
const entry = { gameId: "descriptor", moduleId: "easyrpg", gamePath: sourceRoot, contentRootDir: sourceRoot };
const moduleRoot = GameData.resolveGameModuleDir(userDataDir, entry.gameId, entry.moduleId);

test("EasyRPG enumerates only its obsolete implicit layouts with bounded one-time receipt discovery", t => {
  t.mock.method(fs, "lstatSync", file => {
    assert.ok(["config.ini", "config_sdl1.ini"].some(name => file === path.join(moduleRoot, "config", name)));
    throw Object.assign(new Error("No released config"), {code: "ENOENT"});
  });
  t.mock.method(fs, "opendirSync", file => {
    assert.equal(file, path.join(moduleRoot, "config"));
    throw Object.assign(new Error("No released config folder"), {code: "ENOENT"});
  });
  for (const method of ["statSync", "existsSync", "readdirSync", "readFileSync", "mkdirSync", "writeFileSync", "rmSync"])
    t.mock.method(fs, method, () => { throw new Error(`Unexpected descriptor filesystem operation: ${method}`); });
  const original = structuredClone(entry);
  assert.deepEqual(EasyRPG.legacyGameMirrors(entry, { userDataDir }), [
    { mirrorRoot: path.join(moduleRoot, "writable-input", "files"), sourceRoot },
    { mirrorRoot: path.join(moduleRoot, "saves"), sourceRoot },
    { mirrorRoot: path.join(moduleRoot, "config"), sourceRoot }
  ]);
  assert.deepEqual(entry, original, "describing old layouts never mutates the game record");
});

test("EasyRPG descriptors use original roots from a legacy writable-input record", () => {
  const root = path.join(moduleRoot, "writable-input", "files");
  const previous = { ...entry, contentRootDir: root, moduleData: { writableInput: { schemaVersion: 1, root, sourceRoot } } };
  const descriptors = EasyRPG.legacyGameMirrors(previous, { userDataDir });
  assert.equal(descriptors.length, 3);
  assert.ok(descriptors.every(descriptor => descriptor.sourceRoot === sourceRoot));
  assert.ok(descriptors.every(descriptor => !descriptor.generated?.length), "no game configuration or saves are disposable generated bytes");
  assert.equal(previous.contentRootDir, root);
});

test("EasyRPG retains a legacy folder that is still an explicit save location", () => {
  for (const name of ["saves", "config", path.join("writable-input", "files")]) {
    const oldRoot = path.join(moduleRoot, name);
    for (const saveDirOverride of [oldRoot, path.join(oldRoot, "selected")]) {
      const descriptors = EasyRPG.legacyGameMirrors({ ...entry, saveDirOverride }, { userDataDir });
      assert.equal(descriptors.some(descriptor => descriptor.mirrorRoot === oldRoot), false);
      assert.equal(descriptors.some(descriptor => descriptor.mirrorRoot === moduleRoot), false);
      assert.equal(descriptors.some(descriptor => descriptor.mirrorRoot === path.join(moduleRoot, "exports")), false);
    }
  }
  const separate = EasyRPG.legacyGameMirrors({ ...entry, saveDirOverride: path.resolve("/tmp/explicit-easyrpg-saves") }, { userDataDir });
  assert.equal(separate.length, 3, "an unrelated explicit destination does not hide obsolete default layouts");
});
